// parseHeaderJSON parses a header value that can be either a single JSON object
// string or a JSON array of strings (where the first element is the JSON object).
// This matches the behavior where headers can arrive in either format.
func parseHeaderJSON(header string) (map[string]interface{}, error) {
	header = strings.TrimSpace(header)

	// Try parsing as a single JSON object first.
	var data map[string]interface{}
	if err := json.Unmarshal([]byte(header), &data); err == nil {
		return data, nil
	}

	// Try parsing as a JSON array of strings.
	var arr []string
	if err := json.Unmarshal([]byte(header), &arr); err == nil && len(arr) > 0 {
		if err := json.Unmarshal([]byte(arr[0]), &data); err == nil {
			return data, nil
		}
	}

	return nil, fmt.Errorf("failed to parse header JSON: %s", header)
}

