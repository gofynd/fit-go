// JWTOptions configures the JWT authorisation middleware.
type JWTOptions struct {
	// Secret is the HMAC secret. If empty, JWT_SECRET_DELETE_ENTITY is used.
	Secret string
	// ExpectedPayload is an object or string that must match the decoded token
	// (excluding standard claims like iat, exp, nbf, aud, sub, iss).
	// If nil, the middleware attempts to match company_id from URL params.
	ExpectedPayload interface{}
	// RSAPublicKeyPEM is used for allowed RSA algorithms.
	RSAPublicKeyPEM string
	// AllowedAlgorithms defaults to HS256. Supported values are HS256, HS384,
	// HS512, RS256, RS384, and RS512.
	AllowedAlgorithms []string
	// AllowedClockSkew applies leeway to exp and nbf validation.
	AllowedClockSkew time.Duration
	// Issuer, Audience, and Subject require matching registered claims when set.
	Issuer   string
	Audience string
	Subject  string
}

// standardClaims are JWT registered claim names excluded from payload comparison.
var standardClaims = map[string]struct{}{
	"iat": {}, "exp": {}, "nbf": {}, "aud": {}, "sub": {}, "iss": {},
}

var defaultJWTAlgorithms = []string{"HS256"}

// AuthorizeJWTToken returns a gin middleware that validates a Bearer JWT token
// and optionally checks that the decoded payload matches the
// expected values. Decoded claims are stored in context - retrieve with
// DecodedTokenFromContext.
func AuthorizeJWTToken(opts JWTOptions) gin.HandlerFunc {
	return func(c *gin.Context) {
		secret := opts.Secret
		if secret == "" {
			secret = envGet("JWT_SECRET_DELETE_ENTITY", "")
		}

		// Extract Bearer token
		authHeader := c.GetHeader("Authorization")
		token := strings.TrimPrefix(authHeader, "Bearer ")
		token = strings.TrimSpace(token)
		if token == "" || token == authHeader {
			c.AbortWithStatusJSON(http.StatusUnauthorized, map[string]string{"message": "Unauthorized"})
			return
		}

		algorithms := opts.AllowedAlgorithms
		if len(algorithms) == 0 {
			algorithms = defaultJWTAlgorithms
		}
		decoded, err := verifyJWTToken(token, jwtVerificationOptions{
			Secret:            secret,
			RSAPublicKeyPEM:   opts.RSAPublicKeyPEM,
			AllowedAlgorithms: algorithms,
			AllowedClockSkew:  opts.AllowedClockSkew,
			Issuer:            opts.Issuer,
			Audience:          opts.Audience,
			Subject:           opts.Subject,
		})
		if err != nil {
			c.AbortWithStatusJSON(http.StatusUnauthorized, map[string]string{"message": "Unauthorized"})
			return
		}

		// Store decoded token in gin context and standard context
		c.Set(ginKeyDecodedToken, decoded)
		ctx := context.WithValue(c.Request.Context(), ctxKeyDecodedToken, decoded)
		c.Request = c.Request.WithContext(ctx)

		// Build expected payload
		expected := opts.ExpectedPayload
		if expected == nil {
			companyID := c.Param("company_id")
			if companyID != "" {
				expected = map[string]interface{}{"company_id": companyID}
			}
		}

		// Compare non-standard claims if expected is set
		if expected != nil {
			if !jwtPayloadEqual(expected, decoded) {
				c.AbortWithStatusJSON(http.StatusUnauthorized, map[string]string{"message": "Unauthorized"})
				return
			}
		}

		c.Next()
	}
}

type jwtVerificationOptions struct {
	Secret            string
	RSAPublicKeyPEM   string
	AllowedAlgorithms []string
	AllowedClockSkew  time.Duration
	Issuer            string
	Audience          string
	Subject           string
}

type flexibleClaims struct {
	value     interface{}
	mapClaims jwt.MapClaims
}

func (claims *flexibleClaims) UnmarshalJSON(data []byte) error {
	var object map[string]interface{}
	if err := json.Unmarshal(data, &object); err == nil && object != nil {
		claims.value = object
		claims.mapClaims = jwt.MapClaims(object)
		return nil
	}
	var text string
	if err := json.Unmarshal(data, &text); err != nil {
		return fmt.Errorf("JWT payload must be an object or string: %w", err)
	}
	claims.value = text
	claims.mapClaims = nil
	return nil
}

func (claims *flexibleClaims) GetExpirationTime() (*jwt.NumericDate, error) {
	return claims.mapClaims.GetExpirationTime()
}
func (claims *flexibleClaims) GetIssuedAt() (*jwt.NumericDate, error) {
	return claims.mapClaims.GetIssuedAt()
}
func (claims *flexibleClaims) GetNotBefore() (*jwt.NumericDate, error) {
	return claims.mapClaims.GetNotBefore()
}
func (claims *flexibleClaims) GetIssuer() (string, error)  { return claims.mapClaims.GetIssuer() }
func (claims *flexibleClaims) GetSubject() (string, error) { return claims.mapClaims.GetSubject() }
func (claims *flexibleClaims) GetAudience() (jwt.ClaimStrings, error) {
	return claims.mapClaims.GetAudience()
}

func verifyJWTToken(tokenString string, options jwtVerificationOptions) (interface{}, error) {
	parserOptions := []jwt.ParserOption{jwt.WithValidMethods(options.AllowedAlgorithms)}
	if options.AllowedClockSkew > 0 {
		parserOptions = append(parserOptions, jwt.WithLeeway(options.AllowedClockSkew))
	}
	if options.Issuer != "" {
		parserOptions = append(parserOptions, jwt.WithIssuer(options.Issuer))
	}
	if options.Audience != "" {
		parserOptions = append(parserOptions, jwt.WithAudience(options.Audience))
	}
	if options.Subject != "" {
		parserOptions = append(parserOptions, jwt.WithSubject(options.Subject))
	}

	claims := &flexibleClaims{}
	parsed, err := jwt.ParseWithClaims(tokenString, claims, func(token *jwt.Token) (interface{}, error) {
		switch token.Method.(type) {
		case *jwt.SigningMethodHMAC:
			if options.Secret == "" {
				return nil, fmt.Errorf("no HMAC secret configured")
			}
			return []byte(options.Secret), nil
		case *jwt.SigningMethodRSA:
			if options.RSAPublicKeyPEM == "" {
				return nil, fmt.Errorf("no RSA public key configured")
			}
			return jwt.ParseRSAPublicKeyFromPEM([]byte(options.RSAPublicKeyPEM))
		default:
			return nil, fmt.Errorf("unsupported signing algorithm %s", token.Method.Alg())
		}
	}, parserOptions...)
	if err != nil {
		return nil, fmt.Errorf("JWT verification failed: %w", err)
	}
	if !parsed.Valid || claims.value == nil {
		return nil, fmt.Errorf("JWT is invalid")
	}
	return claims.value, nil
}

// verifyHS256 is retained for package compatibility and delegates to the
// hardened verifier.
func verifyHS256(tokenString, secret string) (map[string]interface{}, error) {
	parts := strings.Split(tokenString, ".")
	if len(parts) != 3 {
		return nil, fmt.Errorf("JWT is malformed")
	}
	headerBytes, err := base64.RawURLEncoding.DecodeString(parts[0])
	if err != nil {
		return nil, fmt.Errorf("JWT is malformed: %w", err)
	}
	var header struct {
		Algorithm string `json:"alg"`
	}
	if err := json.Unmarshal(headerBytes, &header); err != nil {
		return nil, fmt.Errorf("JWT is malformed: %w", err)
	}
	if header.Algorithm != "HS256" {
		return nil, fmt.Errorf("unsupported algorithm %q", header.Algorithm)
	}
	decoded, err := verifyJWTToken(tokenString, jwtVerificationOptions{
		Secret: secret, AllowedAlgorithms: []string{"HS256"},
	})
	if err != nil {
		return nil, err
	}
	claims, ok := decoded.(map[string]interface{})
	if !ok {
		return nil, fmt.Errorf("JWT payload is not an object")
	}
	return claims, nil
}

func jwtPayloadEqual(expected, decoded interface{}) bool {
	switch expectedValue := expected.(type) {
	case map[string]interface{}:
		decodedValue, ok := decoded.(map[string]interface{})
		if !ok {
			return false
		}
		actual := make(map[string]interface{})
		for key, value := range decodedValue {
			if _, standard := standardClaims[key]; !standard {
				actual[key] = value
			}
		}
		return jsonEqual(expectedValue, actual)
	case string:
		decodedValue, ok := decoded.(string)
		return ok && decodedValue == expectedValue
	default:
		return false
	}
}

// jsonEqual compares two maps by marshalling to JSON. This mirrors lodash's
// deep equality for decoded JSON payloads.
func jsonEqual(a, b map[string]interface{}) bool {
	aj, err1 := json.Marshal(a)
	bj, err2 := json.Marshal(b)
	if err1 != nil || err2 != nil {
		return false
	}
	return string(aj) == string(bj)
}

