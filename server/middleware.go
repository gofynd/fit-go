// DecryptFunc is the function signature for decrypting a string value.
// The caller should provide their encryption.Decrypt implementation.
type DecryptFunc func(ciphertext string) (string, error)

// DecryptionMiddleware returns a gin middleware that decrypts specified fields in
// the JSON response body. locations are dot-notation paths (e.g. "data.secret").
func DecryptionMiddleware(locations []string, decrypt DecryptFunc) gin.HandlerFunc {
	return func(c *gin.Context) {
		if len(locations) == 0 || decrypt == nil {
			c.Next()
			return
		}

		// Use a custom response writer to capture the body
		buf := &bytes.Buffer{}
		bw := &bodyWriter{ResponseWriter: c.Writer, buf: buf, statusCode: http.StatusOK}
		c.Writer = bw

		c.Next()

		body := buf.Bytes()
		if len(body) == 0 || bw.statusCode >= 400 {
			// Nothing to decrypt or error response; write as-is
			c.Writer = bw.ResponseWriter
			if len(body) > 0 {
				c.Writer.Write(body)
			}
			return
		}

		var data map[string]interface{}
		if err := json.Unmarshal(body, &data); err != nil {
			// Not JSON; write original
			c.Writer = bw.ResponseWriter
			c.Writer.Write(body)
			return
		}

		// Decrypt each location
		for _, loc := range locations {
			decryptNestedField(data, strings.Split(loc, "."), decrypt)
		}

		result, err := json.Marshal(data)
		if err != nil {
			c.Writer = bw.ResponseWriter
			c.Writer.Write(body)
			return
		}

		c.Writer = bw.ResponseWriter
		c.Writer.Header().Set("Content-Length", strconv.Itoa(len(result)))
		c.Writer.Write(result)
	}
}

// bodyWriter intercepts Write calls to capture the response body for gin.
type bodyWriter struct {
	gin.ResponseWriter
	buf        *bytes.Buffer
	statusCode int
}

func (bw *bodyWriter) WriteHeader(code int) {
	bw.statusCode = code
	// Do NOT forward WriteHeader; we write after decryption.
}

func (bw *bodyWriter) Write(b []byte) (int, error) {
	return bw.buf.Write(b)
}

func (bw *bodyWriter) WriteString(s string) (int, error) {
	return bw.buf.WriteString(s)
}

// decryptNestedField traverses the map following the key path and decrypts
// the leaf value in place.
func decryptNestedField(data map[string]interface{}, keys []string, decrypt DecryptFunc) {
	if len(keys) == 0 {
		return
	}

	current := data
	for i := 0; i < len(keys)-1; i++ {
		next, ok := current[keys[i]].(map[string]interface{})
		if !ok {
			return
		}
		current = next
	}

	lastKey := keys[len(keys)-1]
	val, ok := current[lastKey].(string)
	if !ok {
		return
	}

	decrypted, err := decrypt(val)
	if err != nil {
		slog.Error("DecryptionMiddleware: failed to decrypt field",
			"path", strings.Join(keys, "."),
			"error", err,
		)
		return
	}
	current[lastKey] = decrypted
}

