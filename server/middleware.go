// Middleware is the standard middleware signature used throughout fit.go.
// With gin, this is gin.HandlerFunc.
type Middleware = gin.HandlerFunc

// WrapHTTPMiddleware converts a standard http middleware into a gin.HandlerFunc.
func WrapHTTPMiddleware(mw func(http.Handler) http.Handler) gin.HandlerFunc {
	return func(c *gin.Context) {
		mw(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			c.Request = r
			c.Next()
		})).ServeHTTP(c.Writer, c.Request)
	}
}

// contextKey is an unexported type for context keys defined in this package.
type contextKey int

const (
	ctxKeyApplicationData contextKey = iota
	ctxKeyUserData
	ctxKeyDecodedToken
	ctxKeyRequestID
)

// Gin context key strings for c.Set/c.Get.
const (
	ginKeyApplicationData = "fit.applicationData"
	ginKeyUserData        = "fit.userData"
	ginKeyDecodedToken    = "fit.decodedToken"
	ginKeyRequestID       = "fit.requestID"
)

