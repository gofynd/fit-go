// LogRequestResponseConfig controls the behaviour of the log middleware.
type LogRequestResponseConfig struct {
	// Logger is the structured logger to use. If nil, slog.Default() is used.
	Logger *slog.Logger
	// IncludeHeaders is a comma-separated list of header names to include in logs.
	// Mirrors the INCLUDE_HEADERS_IN_LOG env var.
	IncludeHeaders string
	// ResponseLogSeverity controls the response log level. The default is all-info
	// for fit.js/pyfit parity. Use ResponseLogSeverityStatusBased for services that
	// intentionally want 4xx=WARN and 5xx=ERROR.
	ResponseLogSeverity ResponseLogSeverityMode
	// LegacyOriginalURL keeps the legacy request_url field shape by appending the
	// query string, but values are still allowlist-redacted. The default is
	// path-only, with redacted query params logged separately.
	LegacyOriginalURL bool
	// LegacyTraceClue selects the TraceClue access-log field names and shape:
	// request_url includes a redacted query string, route values are emitted as
	// request_params, and response duration is omitted. FIT_LOG_SCHEMA=traceclue
	// enables the same behavior automatically when this field is false.
	LegacyTraceClue bool
	// MetricsRecorder is an optional callback invoked with method, route, status, and
	// duration so that the caller can record Prometheus histograms.
	MetricsRecorder func(method, route, status string, durationMs float64)
	// DisableLogging suppresses the REQ/RES access-log pair while retaining the
	// middleware's metrics callback. The default is false for compatibility with
	// all existing fit-go callers.
	DisableLogging bool
}

// ResponseLogSeverityMode controls response log levels for LogRequestResponse.
type ResponseLogSeverityMode string

const (
	// ResponseLogSeverityAllInfo logs every response line at INFO. This is the
	// legacy fit.js/pyfit default and remains the zero-value behaviour.
	ResponseLogSeverityAllInfo ResponseLogSeverityMode = "all_info"
	// ResponseLogSeverityStatusBased logs 5xx at ERROR, 4xx at WARN, and everything
	// else at INFO. This preserves the optimized fit-go behavior as an opt-in.
	ResponseLogSeverityStatusBased ResponseLogSeverityMode = "status_based"
)

// LogRequestResponse returns a gin middleware that logs incoming requests and outgoing
// responses. Health-check paths (/_healthz, /_readyz) are skipped.
func LogRequestResponse(cfg LogRequestResponseConfig) gin.HandlerFunc {
	l := cfg.Logger
	if l == nil {
		l = slog.Default()
	}

	return func(c *gin.Context) {
		path := c.Request.URL.Path
		legacyTraceClue := cfg.LegacyTraceClue || traceClueLogSchemaEnabled()
		requestURL := requestURLForLog(c, cfg, legacyTraceClue)

		// Skip health/readiness probes
		if strings.Contains(path, "/_healthz") || strings.Contains(path, "/_readyz") {
			c.Next()
			return
		}

		start := time.Now()

		// Preserve the legacy field names and REQ/RES duplication, but enforce the
		// Commerce telemetry boundary: arbitrary query values and credential headers
		// are never emitted. Pagination/sort controls remain visible through the
		// shared allowlist so logs retain operational value without carrying PII.
		base := []slog.Attr{
			slog.String("request_url", requestURL),
			slog.String("request_method", c.Request.Method),
		}
		if legacyTraceClue {
			base = append(base, slog.Any("request_params", requestParams(c.Params)))
		} else {
			if q := queryParams(c.Request.URL.Query()); q != nil {
				base = append(base, slog.Any("query_params", q))
			}
			if p := pathParams(c.Params); p != nil {
				base = append(base, slog.Any("path_params", p))
			}
		}
		if cfg.IncludeHeaders != "" {
			for _, h := range strings.Split(cfg.IncludeHeaders, ",") {
				if h = strings.TrimSpace(h); h != "" {
					base = append(base, slog.String(h, redact.HeaderValue(h, c.Request.Header.Get(h))))
				}
			}
		}

		// Full-slice cap so REQ/RES appends each allocate — no shared-backing aliasing.
		if !cfg.DisableLogging {
			reqAttrs := append(base[:len(base):len(base)], slog.String("step", "REQ"))
			l.LogAttrs(c.Request.Context(), slog.LevelInfo,
				fmt.Sprintf("[REQ] Incoming %s request for %s", c.Request.Method, requestURL),
				reqAttrs...,
			)
		}

		c.Next()

		duration := time.Since(start)
		statusCode := c.Writer.Status()

		// Record Prometheus metrics via callback
		if cfg.MetricsRecorder != nil {
			// Express labels a matched request with req.baseUrl + req.route.path.
			// Gin's equivalent is FullPath. fit Server mounts generic handlers on
			// /*path, however, so that outer transport route carries no useful
			// service-level cardinality; use the same UUID/numeric fallback that
			// fit.js uses when req.route is unavailable in that case.
			route := c.FullPath()
			if route == "" || strings.HasSuffix(route, "/*path") {
				route = normalizeRoutePath(path)
			}
			cfg.MetricsRecorder(c.Request.Method, route, strconv.Itoa(statusCode), float64(duration.Milliseconds()))
		}

		// Legacy default: single info level. Services that migrated from fit.js v2.9
		// status-based logging can opt in with ResponseLogSeverityStatusBased.
		if !cfg.DisableLogging {
			responseLevel := responseLogLevel(statusCode, cfg)
			resAttrs := append(base[:len(base):len(base)],
				slog.String("step", "RES"),
				slog.Int("response_status", statusCode),
			)
			if !legacyTraceClue {
				// The TraceClue formatter never added middleware duration to its
				// request attributes. Keep duration in the platform schema, where it
				// is useful operational metadata, without contaminating compatibility
				// logs. Preserve the existing key for platform consumers.
				resAttrs = append(resAttrs, slog.Duration("duration", duration))
			}
			l.LogAttrs(c.Request.Context(), responseLevel,
				fmt.Sprintf("[RES] Outgoing %s response from %s", c.Request.Method, requestURL),
				resAttrs...,
			)
		}
	}
}

// GinLogRequestResponse is an alias for LogRequestResponse for use in server.go.
var GinLogRequestResponse = LogRequestResponse

func requestURLForLog(c *gin.Context, cfg LogRequestResponseConfig, legacyTraceClue bool) string {
	if cfg.LegacyOriginalURL || legacyTraceClue || strings.EqualFold(strings.TrimSpace(envGet("FIT_LOG_REQUEST_URL", "")), "original") {
		if query := redact.Query(c.Request.URL.RawQuery, nil); query != "" {
			return c.Request.URL.Path + "?" + query
		}
	}
	return c.Request.URL.Path
}

func traceClueLogSchemaEnabled() bool {
	schema := strings.ToLower(strings.TrimSpace(envGet("FIT_LOG_SCHEMA", "")))
	return schema == "" || schema == "traceclue"
}

func responseLogLevel(statusCode int, cfg LogRequestResponseConfig) slog.Level {
	mode := cfg.ResponseLogSeverity
	if mode == "" {
		mode = ResponseLogSeverityMode(envGet("FIT_RESPONSE_LOG_SEVERITY", ""))
	}
	switch strings.ToLower(strings.TrimSpace(string(mode))) {
	case string(ResponseLogSeverityStatusBased), "status", "status-based":
		if statusCode >= http.StatusInternalServerError {
			return slog.LevelError
		}
		if statusCode >= http.StatusBadRequest {
			return slog.LevelWarn
		}
	}
	return slog.LevelInfo
}

// queryParams retains the legacy structured field while masking every value
// outside the shared pagination/sort allowlist. nil when empty.
func queryParams(v map[string][]string) map[string]string {
	return redact.QueryMap(v, nil)
}

// pathParams renders gin route params (fit.js request_params / pyfit path_params)
// as a key->value map, skipping catch-all (/*wildcard) params. A catch-all
// captures the whole remaining path — always leading-"/" — which just duplicates
// request_url (e.g. a service that mounts a wildcard route + internal dispatch has
// a single catch-all param, adding only noise). Named params (:id) capture one
// segment and never start with "/". Returns nil when nothing meaningful remains.
func pathParams(ps gin.Params) map[string]string {
	if len(ps) == 0 {
		return nil
	}
	out := make(map[string]string, len(ps))
	for _, p := range ps {
		if strings.HasPrefix(p.Value, "/") {
			continue // catch-all wildcard — redundant with request_url
		}
		out[p.Key] = p.Value
	}
	if len(out) == 0 {
		return nil
	}
	return out
}

// requestParams preserves the legacy TraceClue/Winston request_params field:
// it is present as an object even when the route has no named parameters.
func requestParams(ps gin.Params) map[string]string {
	params := pathParams(ps)
	if params == nil {
		return map[string]string{}
	}
	return params
}

