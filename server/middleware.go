// Route path normalization (for logging / Prometheus labels)
// ---------------------------------------------------------------------------

var (
	uuidPattern    = regexp.MustCompile(`/[a-fA-F0-9-]{36}`)
	numericPattern = regexp.MustCompile(`/\d+`)
)

// normalizeRoutePath replaces UUIDs with :uuid and numeric segments with :id.
// UUIDs are matched first to avoid partial replacement by the numeric pattern.
func normalizeRoutePath(path string) string {
	path = uuidPattern.ReplaceAllString(path, "/:uuid")
	path = numericPattern.ReplaceAllString(path, "/:id")
	return path
}

// ---------------------------------------------------------------------------
// responseRecorder captures status code and body for logging.
// (kept for backward compatibility with non-gin code paths)
// ---------------------------------------------------------------------------

type responseRecorder struct {
	http.ResponseWriter
	statusCode int
	written    bool
}

func newResponseRecorder(w http.ResponseWriter) *responseRecorder {
	return &responseRecorder{ResponseWriter: w, statusCode: http.StatusOK}
}

func (r *responseRecorder) WriteHeader(code int) {
	if !r.written {
		r.statusCode = code
		r.written = true
	}
	r.ResponseWriter.WriteHeader(code)
}

func (r *responseRecorder) Write(b []byte) (int, error) {
	if !r.written {
		r.statusCode = http.StatusOK
		r.written = true
	}
	return r.ResponseWriter.Write(b)
}

// Unwrap provides access to the underlying ResponseWriter for http.Flusher etc.
func (r *responseRecorder) Unwrap() http.ResponseWriter {
	return r.ResponseWriter
}

