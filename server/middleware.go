// GinParseApplicationData is a gin middleware that parses the x-application-data
// header (JSON) and stores the result in the gin context.
// Retrieve it with ApplicationDataFromContext.
func GinParseApplicationData(c *gin.Context) {
	header := c.GetHeader("x-application-data")
	if header != "" {
		data, err := parseHeaderJSON(header)
		if err != nil {
			c.AbortWithStatusJSON(http.StatusUnauthorized, map[string]interface{}{
				"error": map[string]interface{}{
					"code":    "APPLICATION_HEADER_JSON_PARSE_FAILURE",
					"message": "failed to parse x-application-data header",
					"meta": map[string]interface{}{
						"rawApplicationHeader": header,
					},
				},
			})
			return
		}
		c.Set(ginKeyApplicationData, data)
		ctx := context.WithValue(c.Request.Context(), ctxKeyApplicationData, data)
		c.Request = c.Request.WithContext(ctx)
	}
	c.Next()
}

