// RequestID generates a unique request ID and stores it in the gin context
// and the X-Request-ID response header.
func RequestID() gin.HandlerFunc {
	return func(c *gin.Context) {
		id := c.GetHeader("X-Request-ID")
		if id == "" {
			id = generateRequestID()
			// Also set it on the REQUEST header so later middleware that reads
			// c.GetHeader("x-request-id") (e.g. OTelMiddleware's span attribute)
			// sees the minted id, not just the response header.
			c.Request.Header.Set("X-Request-ID", id)
		}
		c.Header("X-Request-ID", id)
		c.Set(ginKeyRequestID, id)
		ctx := context.WithValue(c.Request.Context(), ctxKeyRequestID, id)
		c.Request = c.Request.WithContext(ctx)
		c.Next()
	}
}

// generateRequestID creates a simple UUID v4-like identifier without external deps.
func generateRequestID() string {
	b := make([]byte, 16)
	_, _ = io.ReadFull(cryptoRandReader(), b)
	b[6] = (b[6] & 0x0f) | 0x40 // version 4
	b[8] = (b[8] & 0x3f) | 0x80 // variant 10
	return fmt.Sprintf("%08x-%04x-%04x-%04x-%012x",
		b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}

// cryptoRandReader returns crypto/rand.Reader. Separated for testability.
func cryptoRandReader() io.Reader {
	return cryptoRandReaderInstance
}

