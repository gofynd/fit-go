// ApplicationDataFromContext returns the parsed x-application-data header value
// that was attached by the ParseApplicationData middleware.
func ApplicationDataFromContext(ctx context.Context) map[string]interface{} {
	// Try gin context first
	if gc, ok := ctx.(*gin.Context); ok {
		if v, exists := gc.Get(ginKeyApplicationData); exists {
			if m, ok := v.(map[string]interface{}); ok {
				return m
			}
		}
	}
	v, _ := ctx.Value(ctxKeyApplicationData).(map[string]interface{})
	return v
}

