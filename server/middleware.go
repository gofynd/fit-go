// MaxPayloadSize limits the request body to the given size string.
// Accepted formats: "2mb", "500kb", "1gb". Defaults to 2MB if parsing fails.
// This mirrors the MAX_REQUEST_PAYLOAD_SIZE env var.
func MaxPayloadSize(size string) gin.HandlerFunc {
	limit := parseSize(size)
	return func(c *gin.Context) {
		if c.Request.Body != nil {
			c.Request.Body = http.MaxBytesReader(c.Writer, c.Request.Body, limit)
		}
		c.Next()
	}
}

// GinMaxPayloadSize is an alias for MaxPayloadSize for use in server.go.
var GinMaxPayloadSize = MaxPayloadSize

// parseSize converts a human-readable size string to bytes.
func parseSize(s string) int64 {
	s = strings.TrimSpace(strings.ToLower(s))
	if s == "" {
		return 2 * 1024 * 1024
	}

	var multiplier int64 = 1
	numStr := s

	switch {
	case strings.HasSuffix(s, "gb"):
		multiplier = 1024 * 1024 * 1024
		numStr = strings.TrimSuffix(s, "gb")
	case strings.HasSuffix(s, "mb"):
		multiplier = 1024 * 1024
		numStr = strings.TrimSuffix(s, "mb")
	case strings.HasSuffix(s, "kb"):
		multiplier = 1024
		numStr = strings.TrimSuffix(s, "kb")
	case strings.HasSuffix(s, "b"):
		numStr = strings.TrimSuffix(s, "b")
	}

	n, err := strconv.ParseInt(strings.TrimSpace(numStr), 10, 64)
	if err != nil || n <= 0 {
		return 2 * 1024 * 1024
	}
	return n * multiplier
}

