// ApplicationDataFromContext returns the parsed x-application-data header value
// that was attached by the ParseApplicationData middleware.
func ApplicationDataFromContext(ctx context.Context) map[string]interface{} {
	// Try gin context first
	if gc, ok := ctx.(*gin.Context); ok {
		if v, exists := gc.Get(ginKeyApplicationData); exists {
			if m, ok := v.(map[string]interface{}); ok {
				return m
			}
		}
	}
	v, _ := ctx.Value(ctxKeyApplicationData).(map[string]interface{})
	return v
}

// UserDataFromContext returns the parsed x-user-data header value
// that was attached by the ParseUserData middleware.
func UserDataFromContext(ctx context.Context) map[string]interface{} {
	if gc, ok := ctx.(*gin.Context); ok {
		if v, exists := gc.Get(ginKeyUserData); exists {
			if m, ok := v.(map[string]interface{}); ok {
				return m
			}
		}
	}
	v, _ := ctx.Value(ctxKeyUserData).(map[string]interface{})
	return v
}

// DecodedTokenFromContext returns the decoded JWT claims that were
// attached by the AuthorizeJWTToken middleware.
func DecodedTokenFromContext(ctx context.Context) map[string]interface{} {
	value := DecodedTokenValueFromContext(ctx)
	claims, _ := value.(map[string]interface{})
	return claims
}

// DecodedTokenValueFromContext returns either an object claims map or a string
// payload, matching jsonwebtoken's decoded payload forms.
func DecodedTokenValueFromContext(ctx context.Context) interface{} {
	if gc, ok := ctx.(*gin.Context); ok {
		if v, exists := gc.Get(ginKeyDecodedToken); exists {
			return v
		}
	}
	return ctx.Value(ctxKeyDecodedToken)
}

// RequestIDFromContext returns the request ID generated by the RequestID middleware.
func RequestIDFromContext(ctx context.Context) string {
	if gc, ok := ctx.(*gin.Context); ok {
		if v, exists := gc.Get(ginKeyRequestID); exists {
			if s, ok := v.(string); ok {
				return s
			}
		}
	}
	v, _ := ctx.Value(ctxKeyRequestID).(string)
	return v
}

// ---------------------------------------------------------------------------
// Route path normalization (for logging / Prometheus labels)
// ---------------------------------------------------------------------------

var (
	uuidPattern    = regexp.MustCompile(`/[a-fA-F0-9-]{36}`)
	numericPattern = regexp.MustCompile(`/\d+`)
)

// normalizeRoutePath replaces UUIDs with :uuid and numeric segments with :id.
// UUIDs are matched first to avoid partial replacement by the numeric pattern.
func normalizeRoutePath(path string) string {
	path = uuidPattern.ReplaceAllString(path, "/:uuid")
	path = numericPattern.ReplaceAllString(path, "/:id")
	return path
}

// ---------------------------------------------------------------------------
// responseRecorder captures status code and body for logging.
// (kept for backward compatibility with non-gin code paths)
// ---------------------------------------------------------------------------

type responseRecorder struct {
	http.ResponseWriter
	statusCode int
	written    bool
}

func newResponseRecorder(w http.ResponseWriter) *responseRecorder {
	return &responseRecorder{ResponseWriter: w, statusCode: http.StatusOK}
}

func (r *responseRecorder) WriteHeader(code int) {
	if !r.written {
		r.statusCode = code
		r.written = true
	}
	r.ResponseWriter.WriteHeader(code)
}

func (r *responseRecorder) Write(b []byte) (int, error) {
	if !r.written {
		r.statusCode = http.StatusOK
		r.written = true
	}
	return r.ResponseWriter.Write(b)
}

// Unwrap provides access to the underlying ResponseWriter for http.Flusher etc.
func (r *responseRecorder) Unwrap() http.ResponseWriter {
	return r.ResponseWriter
}

