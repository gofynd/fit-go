// ErrorHandler is a gin middleware that catches panics and returns structured JSON
// error responses. If the recovered value is a *errors.FitError, its HTTP status
// and structured body are used. Otherwise a 400 Bad Request is returned.
func ErrorHandler(logger *slog.Logger) gin.HandlerFunc {
	if logger == nil {
		logger = slog.Default()
	}
	return func(c *gin.Context) {
		defer func() {
			if rv := recover(); rv != nil {
				logger.Error("panic recovered in ErrorHandler",
					"error", rv,
					"stack", string(debug.Stack()),
					"path", c.Request.URL.Path,
				)

				switch e := rv.(type) {
				case *errors.FitError:
					status := e.HTTPStatusCode
					if status < 200 || status > 599 {
						status = http.StatusInternalServerError
					}
					c.AbortWithStatusJSON(status, map[string]interface{}{
						"error": map[string]interface{}{
							"code":    e.Code,
							"message": e.GetMessage(),
							"meta":    e.Meta,
						},
					})
				case error:
					c.AbortWithStatusJSON(http.StatusBadRequest, map[string]interface{}{
						"error": map[string]interface{}{
							"message": e.Error(),
						},
					})
				default:
					c.AbortWithStatusJSON(http.StatusInternalServerError, map[string]interface{}{
						"error": map[string]interface{}{
							"message": fmt.Sprintf("%v", rv),
						},
					})
				}
			}
		}()

		c.Next()
	}
}

